import fs from "fs";
import path from "path";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";
import { fileURLToPath } from "url";
import dotenv from "dotenv";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

dotenv.config({ quiet: true });

const colors = {
  reset: "\x1b[0m",
  bright: "\x1b[1m",
  green: "\x1b[32m",
  blue: "\x1b[34m",
  yellow: "\x1b[33m",
};

const openApiUrl = process.env.OPENAPI_URL;

if (!openApiUrl) {
  console.error(`${colors.yellow}OPENAPI_URL is not set${colors.reset}`);
  process.exit(1);
}

const NULL = ts.factory.createLiteralTypeNode(ts.factory.createNull());
const FILE = ts.factory.createTypeReferenceNode(
  ts.factory.createIdentifier("File"),
);
const BLOB = ts.factory.createTypeReferenceNode(
  ts.factory.createIdentifier("Blob"),
);

const header = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;

console.log(
  `${colors.blue}${colors.bright}Generating types from ${openApiUrl}...${colors.reset}`,
);

const ast = await openapiTS(new URL(openApiUrl), {
  transform(schemaObject, metadata) {
    if (schemaObject.format === "binary") {
      if (metadata.path.includes("multipart~1form-data")) {
        return schemaObject.nullable
          ? ts.factory.createUnionTypeNode([FILE, NULL])
          : FILE;
      }
      if (metadata.path.includes("application~1octet-stream")) {
        return schemaObject.nullable
          ? ts.factory.createUnionTypeNode([BLOB, NULL])
          : BLOB;
      }
    }
  },
});

console.log(`${colors.yellow}Processing types...${colors.reset}`);
const content = header + astToString(ast);

const filePath = path.join(__dirname, "../src/lib/api/openapi.ts");
fs.writeFileSync(filePath, content);
console.log(`${colors.green}✓ Done: src/lib/api/openapi.ts${colors.reset}`);
